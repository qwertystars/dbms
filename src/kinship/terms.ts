/** Flat rows mirroring migrations seed data (lang, relation_key, term, gloss). */
export const KIN_TERM_ROWS: Array<{ lang: 'en' | 'hi' | 'ta' | 'bn'; relation_key: string; term: string; gloss: string }> =
  (Object.keys(TERMS) as Array<keyof typeof TERMS>).flatMap(lang =>
    Object.entries(TERMS[lang]).map(([relation_key, row]) => ({ lang, relation_key, ...row })),
  );

export function resolveTerms(relationKey: string): {
  en: TermRow; hi: TermRow; ta: TermRow; bn: TermRow; gloss: string;
} {
  const pick = (lang: keyof typeof TERMS): TermRow =>
    TERMS[lang][relationKey] ?? { term: relationKey, gloss: '' };
  const en = pick('en');
  return { en, hi: pick('hi'), ta: pick('ta'), bn: pick('bn'), gloss: en.gloss };
}
